CREATE OR REPLACE FUNCTION add_tenant_fk(
  child_table TEXT,
  child_column TEXT,
  parent_table TEXT,
  constraint_name TEXT
) RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
  IF to_regclass('public.' || child_table) IS NULL OR to_regclass('public.' || parent_table) IS NULL THEN RETURN; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = child_table AND column_name = child_column
  ) THEN RETURN; END IF;
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = constraint_name AND conrelid = to_regclass('public.' || child_table)) THEN RETURN; END IF;
  EXECUTE format(
    'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I, society_id) REFERENCES %I(id, society_id) ON DELETE RESTRICT',
    child_table, constraint_name, child_column, parent_table
  );
END $$;

