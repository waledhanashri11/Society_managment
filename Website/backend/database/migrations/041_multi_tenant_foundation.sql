CREATE OR REPLACE FUNCTION app_current_society_id()
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('app.current_society_id', true), '')::BIGINT
$$;

CREATE OR REPLACE FUNCTION app_tenant_bypass()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
  SELECT COALESCE(current_setting('app.tenant_bypass', true), '') = 'on'
$$;

-- Direct tenant keys are used on security boundaries and high-volume module
-- roots. Child rows also receive a key so RLS protects accidental unscoped
-- joins, updates and deletes at the database boundary.
DO $$
DECLARE
  table_name TEXT;
  tenant_tables TEXT[] := ARRAY[
    'users','flats','flat_types','resident_flat_assignments','flat_transfer_history',
    'maintenance','maintenance_bills','maintenance_bill_items','maintenance_categories',
    'resident_maintenance_categories','flat_category_assignments','maintenance_settings',
    'late_fee_rules','maintenance_expenses','maintenance_disputes','maintenance_audit_logs',
    'maintenance_writeoffs','write_offs','maintenance_billing_cycles','billing_cycle_locks',
    'billing_override_audit_log','payments','payment_maintenance','payment_status_history',
    'ledger_transactions','accounting_opening_balances','society_opening_balances',
    'complaints','complaint_audit_logs','notices','notice_polls','notice_poll_options',
    'notice_poll_votes','events','meetings','meeting_agendas','meeting_attendance',
    'meeting_reports','meeting_actions','meeting_votes','meeting_resident_votes',
    'meeting_documents','meeting_fines','meeting_comments','noc_types','noc_requests',
    'noc_audit_logs','society_rules','society_rule_acknowledgements','notifications',
    'admin_notification_reads','staff','visitors','parcels','activities','app_settings',
    'password_reset_tokens'
  ];
BEGIN
  FOREACH table_name IN ARRAY tenant_tables LOOP
    IF to_regclass('public.' || table_name) IS NOT NULL THEN
      EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS society_id BIGINT', table_name);
      EXECUTE format('UPDATE %I SET society_id = 1 WHERE society_id IS NULL', table_name);
      EXECUTE format('ALTER TABLE %I ALTER COLUMN society_id SET DEFAULT app_current_society_id()', table_name);
      EXECUTE format('ALTER TABLE %I ALTER COLUMN society_id SET NOT NULL', table_name);
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = to_regclass('public.' || table_name)
          AND conname = table_name || '_society_id_fkey'
      ) THEN
        EXECUTE format(
          'ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (society_id) REFERENCES societies(id) ON DELETE RESTRICT',
          table_name, table_name || '_society_id_fkey'
        );
      END IF;
      EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (society_id)', 'idx_' || table_name || '_society', table_name);
    END IF;
  END LOOP;
END $$;

