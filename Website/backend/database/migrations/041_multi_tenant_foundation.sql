-- Database-enforced tenant isolation. FORCE also protects against accidental
-- unscoped queries executed by the table owner used by this application.
DO $$
DECLARE
  table_name TEXT;
BEGIN
  FOR table_name IN
    SELECT c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'public' AND c.column_name = 'society_id' AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON %I USING (society_id = app_current_society_id() OR app_tenant_bypass()) WITH CHECK (society_id = app_current_society_id() OR app_tenant_bypass())',
      table_name
    );
  END LOOP;
END $$;

